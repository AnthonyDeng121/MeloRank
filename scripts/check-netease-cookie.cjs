const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const compile = file => ts.transpileModule(fs.readFileSync(file, 'utf8').replaceAll('import.meta.env', 'env'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const cookies = { exports: {} };
vm.runInNewContext(compile('src/app/services/neteaseCookie.ts'), cookies);
const { normalizeNeteaseCookie } = cookies.exports;
assert.equal(normalizeNeteaseCookie('MUSIC_U=fixture==; unrelated=secret; __csrf=fixture-csrf;'), 'MUSIC_U=fixture==; __csrf=fixture-csrf;');
for (const raw of ['', 'MUSIC_A=guest;', 'MUSIC_U=;', 'MUSIC_U=fixture;\nHeader: bad']) assert.throws(() => normalizeNeteaseCookie(raw));
const values = new Map([['neteaseCookie', 'MUSIC_U=existing;']]);
const sessionStorage = { getItem: key => values.get(key), setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) };
let calls = [], events = 0, status = 200, account = { userId: 7 }, controller;
const sandbox = { exports: {}, env: {}, AbortSignal, Event, sessionStorage, require: () => cookies.exports, window: { dispatchEvent: () => events++ }, fetch: async (url, options) => {
  calls.push({ url, options });
  return { ok: status === 200, status, json: async () => { if (controller) controller.abort(); return status === 200 ? account : { error: '登录已失效' }; } };
} };
vm.runInNewContext(compile('src/app/services/musicPlatforms.ts'), sandbox);
const { netease } = sandbox.exports;
(async () => {
  const signal = new AbortController().signal;
  await assert.rejects(() => netease.connectCookie('not-a-cookie', signal));
  assert.equal(calls.length, 0);
  status = 401;
  await assert.rejects(() => netease.connectCookie('MUSIC_U=bad;', signal));
  assert.equal(sessionStorage.getItem('neteaseCookie'), 'MUSIC_U=existing;');
  status = 200; account = {};
  await assert.rejects(() => netease.connectCookie('MUSIC_U=bad;', signal));
  assert.equal(events, 0);
  account = { userId: 7 }; controller = new AbortController();
  await assert.rejects(() => netease.connectCookie('MUSIC_U=cancelled;', controller.signal));
  assert.equal(events, 0);
  assert.equal(sessionStorage.getItem('neteaseCookie'), 'MUSIC_U=existing;');
  controller = null;
  await netease.connectCookie('MUSIC_U=fixture==; unrelated=secret;', signal);
  assert.equal(sessionStorage.getItem('neteaseCookie'), 'MUSIC_U=fixture==;');
  assert.equal(calls.at(-1).options.headers['X-Netease-Cookie'], 'MUSIC_U=fixture==;');
  assert.ok(calls.at(-1).url.endsWith('/account'));
  assert.equal(events, 1);
  console.log('PASS Cookie validation, credential filtering, account verification, cancellation and existing-session preservation');
})().catch(error => { console.error(error); process.exitCode = 1; });
