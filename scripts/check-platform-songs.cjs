const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const calls = [];
const qqMusicService = { searchWithType: async (...args) => { calls.push(['qq', ...args]); return { qq: true }; }, getSongUrl: async id => { calls.push(['qq-url', id]); return { url: 'qq' }; }, getLyric: async id => { calls.push(['qq-lyric', id]); return {}; } };
let mismatchedAlbum = false;
const fixture = { id: 7, name: 'Song', ar: [{ name: 'Artist' }], al: { name: 'Album', picUrl: 'https://example.com/netease.jpg' }, dt: 90000 };
const netease = { request: async (path, body) => {
  calls.push(['netease', path, body]);
  if (path === 'search') return { songs: [fixture], total: 1 };
  if (path === 'playback') return { url: 'https://music.126.net/fixture.mp3', isPreview: false };
  if (path === 'album-search') return { albums: [{ id: 4, name: mismatchedAlbum ? 'Other Album' : 'Album', artists: [{ name: 'Artist' }] }] };
  if (path === 'collection') return { items: [{ neteaseTrack: fixture }], hasMore: false };
  return { lyric: '[00:01]fixture' };
} };
const spotify = { request: async path => { calls.push(['spotify', path]); return { tracks: { items: [{ id: 'abc', name: 'Spotify track', artists: [], album: {} }], total: 1 } }; } };
const sandbox = { exports: {}, require: path => path === './musicPlatforms' ? { netease, spotify } : { qqMusicService }, URLSearchParams };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/app/services/platformSongs.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, sandbox);
const service = sandbox.exports;
(async () => {
  const result = await service.searchPlatform('netease', 'query', 10, 2);
  const song = result.response.data.song.list[0];
  assert.equal(song.songmid, 'netease:7'); assert.equal(song.duration, 90); assert.equal(song.providerId, '7');
  assert.equal(calls[0][2].offset, 10);
  assert.equal(service.songCover(song), 'https://example.com/netease.jpg');
  assert.equal((await service.platformSongUrl(song)).data.playUrl['netease:7'].url, 'https://music.126.net/fixture.mp3');
  assert.equal((await service.platformLyric(song)).response.lyric, '[00:01]fixture');
  assert.ok(calls.every(call => call[0] === 'netease'), 'NetEase must not call QQ');
  assert.equal((await service.platformAlbumTracks('netease', 'Album', 'Artist', ''))[0].songmid, 'netease:7');
  mismatchedAlbum = true;
  await assert.rejects(() => service.platformAlbumTracks('netease', 'Album', 'Artist', ''));
  const spot = (await service.searchPlatform('spotify', 'query', 10, 1)).response.data.song.list[0];
  assert.equal(spot.uri, 'spotify:track:abc');
  await assert.rejects(() => service.platformSongUrl(spot));
  await assert.rejects(() => service.platformPlayableUrl(spot));
  assert.equal(calls.filter(call => call[0].startsWith('qq')).length, 0);
  await service.searchPlatform('qq', 'query', 10, 1);
  await service.platformSongUrl({ songmid: 'qq-id' });
  assert.equal(calls.at(-1)[0], 'qq-url');
  console.log('PASS provider-specific search, playback, lyrics, normalized IDs, covers and no cross-provider fallback');
})().catch(error => { console.error(error); process.exitCode = 1; });
