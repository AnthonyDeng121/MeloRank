const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync('src/app/services/searchVersions.ts', 'utf8').replace(/import .*?;\s*/, '');
const sandbox = { exports: {}, qqMusicService: { searchWithType: async (query) => ({ response: { data: { album: { totalnum: 1, list: query === 'Manchild' ? [clean] : [explicit, unrelated] } } } }) } };
const clean = { mid: 'clean', name: 'Manchild', singer: [{ name: 'Sabrina Carpenter' }] };
const explicit = { mid: 'explicit', name: 'Manchild (Explicit)', singer: [{ name: 'Sabrina Carpenter' }] };
const unrelated = { mid: 'other', name: 'Manchild (Explicit)', singer: [{ name: 'Other Artist' }] };
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, sandbox);
(async () => {
  const merged = sandbox.exports.mergeSearchVersions([clean], [explicit, clean], 'albums');
  assert.deepEqual(Array.from(merged, item => item.mid), ['explicit', 'clean']);
  const songs = sandbox.exports.mergeSearchVersions([{ songmid: 'a', songname: 'Song', albumname: 'Album', singer: [] }], [{ songmid: 'b', songname: 'Song', albumname: 'Album (Explicit)', singer: [] }], 'songs');
  assert.deepEqual(Array.from(songs, item => item.songmid), ['b', 'a']);
  const result = await sandbox.exports.searchQQVersions('Manchild', 'albums', 50, 1);
  assert.deepEqual(Array.from(result.response.data.album.list, item => item.mid), ['explicit', 'clean']);
  assert.equal(result.response.data.album.totalnum, 2);
  sandbox.qqMusicService.searchWithType = async query => { if (query !== 'Other') throw new Error('offline'); return { response: { data: { album: { list: [clean] } } } }; };
  assert.equal((await sandbox.exports.searchQQVersions('Other', 'albums', 10, 1)).response.data.album.list[0].mid, 'clean');
  const originals = Array.from({ length: 20 }, (_, i) => ({ mid: `release-${i}`, name: `Song ${i}`, singer: [] }));
  const bonus = { mid: 'explicit-extra', name: 'Song 0 (Explicit)', singer: [] };
  sandbox.qqMusicService.searchWithType = async (query, limit, kind, page) => ({ response: { data: { album: { totalnum: 20, list: query === 'Paging' ? originals.slice((page - 1) * limit, page * limit) : [bonus] } } } });
  const pages = [];
  for (let page = 1; page <= 3; page++) pages.push((await sandbox.exports.searchQQVersions('Paging', 'albums', 10, page)).response.data.album);
  assert.deepEqual(pages.map(page => page.list.length), [10, 10, 1]);
  assert.equal(pages[0].list[0].mid, 'explicit-extra');
  assert.equal(new Set(pages.flatMap(page => Array.from(page.list, item => item.mid))).size, 21);
  assert.equal(pages[2].totalnum, 21);
  assert.deepEqual(Array.from((await sandbox.exports.searchQQVersions('Paging', 'albums', 10, 1)).response.data.album.list, item => item.mid), Array.from(pages[0].list, item => item.mid));
  console.log('PASS release ID deduplication, Explicit priority, artist isolation, totals and supplementary request failure');
})().catch(error => { console.error(error); process.exitCode = 1; });
